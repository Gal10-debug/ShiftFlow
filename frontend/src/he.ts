export function message(error: unknown) {
  if (
    error instanceof Error &&
    error.message === "VALIDATION_ERROR" &&
    "fieldErrors" in error &&
    error.fieldErrors &&
    typeof error.fieldErrors === "object"
  ) {
    const labels: Record<string, string> = {
      firstName: he.firstName,
      lastName: he.lastName,
      username: he.username,
      initialPassword: he.initialPassword,
      temporaryPassword: he.initialPassword,
      roles: he.roles,
    };
    const details = Object.entries(error.fieldErrors).flatMap(
      ([field, code]) =>
        Object.hasOwn(labels, field) &&
        typeof code === "string" &&
        Object.hasOwn(he.errors, code)
          ? [`${labels[field]}: ${he.errors[code as keyof typeof he.errors]}`]
          : [],
    );
    if (details.length) return details.join(" ");
  }
  if (
    error instanceof Error &&
    error.message === "WEEKLY_BLOCK_LIMIT" &&
    "weekStartsOn" in error &&
    typeof error.weekStartsOn === "string"
  )
    return `${he.errors.WEEKLY_BLOCK_LIMIT} השבוע שמתחיל ב־${error.weekStartsOn.split("-").reverse().join("/")}.`;
  return error instanceof Error && error.message in he.errors
    ? he.errors[error.message as keyof typeof he.errors]
    : he.errors.INTERNAL_ERROR;
}
export function formatDate(value: string) {
  const parts = new Intl.DateTimeFormat("he-IL", {
    day: "2-digit",
    month: "2-digit",
    year: "numeric",
    timeZone: "Asia/Jerusalem",
  }).formatToParts(new Date(value));
  return ["day", "month", "year"]
    .map((type) => parts.find((p) => p.type === type)?.value)
    .join("/");
}
